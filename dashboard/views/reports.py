from __future__ import annotations

from datetime import datetime

import streamlit as st

from businesspulse.business_analysis.store import audit
from businesspulse.reports import builder
from dashboard import components as ui

REPORTS = {
    "KPI report": lambda f: builder.kpi_report(f["start"], f["end"]),
    "Sales analysis report": lambda f: builder.sales_report(f["start"], f["end"]),
    "Customer analysis report": lambda f: builder.customer_report(),
    "Data quality report": lambda f: builder.data_quality_report(),
    "Business requirements, KPIs & decision register": lambda f: builder.ba_report(),
}


def render() -> None:
    ui.page_header("Reports & Exports", "Excel / CSV reports and executive summaries built from processed data.")
    if not ui.require_warehouse():
        return
    f = ui.filters()
    u = ui.user()
    st.caption(f"Reporting period from sidebar: {f['start']} → {f['end']}")
    name = st.selectbox("Report", list(REPORTS))
    if st.button("Build report", type="primary"):
        with st.spinner("Building report from the warehouse…"):
            sheets = REPORTS[name](f)
            data = builder.to_excel(sheets, {"Report": name, "Period": f"{f['start']} to {f['end']}",
                                             "Generated by": u.username})
        st.session_state["report"] = (name, sheets, data)
        audit(u.username, u.role, "export_report", "reports", name)
    if "report" in st.session_state:
        rname, sheets, data = st.session_state["report"]
        st.download_button(f"⬇ {rname} (.xlsx)", data, f"{rname.lower().replace(' ', '_').replace(',', '')}_"
                           f"{datetime.now():%Y%m%d}.xlsx",
                           "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", type="primary")
        for sname, df in sheets.items():
            with st.expander(f"{sname} ({len(df):,} rows)"):
                st.dataframe(df.head(500), hide_index=True, width="stretch")
                st.download_button(f"⬇ {sname}.csv", df.to_csv(index=False).encode(), f"{sname}.csv", "text/csv",
                                   key=f"csv_{sname}")
    st.divider()
    st.markdown("### Executive summary")
    if st.button("Generate executive summary"):
        with st.spinner("Summarising…"):
            md = builder.executive_summary(f["start"], f["end"])
        st.session_state["exec_md"] = md
        audit(u.username, u.role, "export_exec_summary", "reports")
    if "exec_md" in st.session_state:
        st.download_button("⬇ Executive summary (.md)", st.session_state["exec_md"], "executive_summary.md", "text/markdown")
        with st.container(border=True):
            st.markdown(st.session_state["exec_md"])
    if u.role == "Administrator":
        st.divider()
        st.markdown("### Audit log (administrators)")
        from businesspulse.db import app_query
        st.dataframe(app_query("select * from audit_log order by id desc limit 500"), hide_index=True, width="stretch")
