from __future__ import annotations

import streamlit as st

from businesspulse.config import settings
from businesspulse.insights import engine
from dashboard import components as ui


def render() -> None:
    ui.page_header("AI Insights", "Plain-language answers grounded in verified query results.", "mixed")
    if not ui.require_warehouse():
        return
    mode = ("Claude (re-phrasing only, numbers checked against evidence)"
            if (settings.llm_provider or "").lower() == "anthropic" else "Deterministic rule-based engine")
    st.caption(f"Engine: **{mode}**. Every number comes from warehouse queries; observations are separated from "
               "recommendations; correlation is never presented as causation.")
    q = st.radio("Ask a question", list(engine.QUESTIONS), key="ins_q")
    free = st.text_input("…or type your own (routed to the closest verified analysis)", key="ins_free")
    question = free.strip() or q
    with st.spinner("Running analysis…"):
        ins = engine.answer(question)
    if ins.data_basis == "synthetic":
        ui.synthetic_banner()
    with st.container(border=True):
        st.markdown(ins.narrative or "\n".join(f"- {x}" for x in ins.limitations))
    st.caption(f"Generated by: {ins.engine}")
    if not ins.evidence.empty:
        st.markdown("**Supporting metrics**")
        st.dataframe(ins.evidence, hide_index=True, width="stretch")
    st.download_button("⬇ Evidence (JSON)", engine.evidence_json(ins), "insight_evidence.json", "application/json")
